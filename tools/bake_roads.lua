-- How each entrance graph edge weighs road travel while Follow roads is on, baked from the roads painted on the
-- walking maps. Run from the repo root after rebaking a walking map or changing Data/RoadCells.lua:
-- luajit tools/bake_roads.lua > Data/RoadEdges.lua
local ns = {}
for _, file in ipairs({
	"Data/Routes.lua",
	"Data/Transports.lua",
	"Data/Taxi.lua",
	"Data/Portals.lua",
	"Data/Teleports.lua",
	"Data/RoadCells.lua",
	"Routing/PathGrid.lua",
	"Routing/Path.lua",
	"Routing/PathJobs.lua",
	"Routing/Planner.lua",
}) do
	assert(loadfile(file))("ShortestPathForever", ns)
end
for _, map in ipairs({ 0, 1, 2991 }) do
	assert(loadfile("tools/load_nav.lua"))(map)
end
local Path = ns.Path

print("-- Generated by tools/bake_roads.lua; do not edit.")
print("-- Road ratios for each entrance graph edge, per Nav cluster (RoadCells.lua decides which cells are road):")
print('-- edges in entrance order. A run of default edges is "=" and its length in two base64 symbols; any other')
print("-- edge is four symbols: preference and real ratio for walking, then for water walking. A ratio q is")
print("-- 1 + q / 63 * 0.5, so 0 is the road itself and 63 is off it; a default edge is 63 and 0 in both modes.")
print("local ns = select(2, ...)")
print("")
print("-- stylua: ignore")
print("ns.RoadEdges = {")
for _, map in ipairs({ 0, 1, 2991 }) do
	local edges = Path.BakeRoadEdges(map)
	local keys = {}
	for k in pairs(edges) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	io.stderr:write(("map %d: %d clusters with road edges\n"):format(map, #keys))
	print(("\t[%d] = {"):format(map))
	for _, k in ipairs(keys) do
		print(('\t\t[%d] = "%s",'):format(k + 1, edges[k]))
	end
	print("\t},")
end
print("}")
