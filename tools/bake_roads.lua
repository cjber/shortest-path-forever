-- How each entrance graph edge weighs road travel while Follow roads is on, baked from the roads painted on the
-- walking maps. Run from the repo root after rebaking a walking map or changing Data/RoadCells.lua:
-- luajit tools/bake_roads.lua > Data/RoadEdges.lua
-- Each map bakes in its own child process (`--map <id>`) at the same time; the parent writes their blocks in map
-- order, so the output does not depend on which child finishes first.
local MAPS = { 0, 1, 2991 }

local function BakeMap(map)
	local ns = {}
	for _, file in ipairs({
		"Data/Routes.lua",
		"Data/Transports.lua",
		"Data/Taxi.lua",
		"Data/Portals.lua",
		"Data/Teleports.lua",
		"Data/RoadCells.lua",
		"Routing/PathGrid.lua",
		"Routing/Path.lua",
		"Routing/PathJobs.lua",
		"Routing/Planner.lua",
	}) do
		assert(loadfile(file))("ShortestPathForever", ns)
	end
	for _, nav in ipairs(MAPS) do
		assert(loadfile("tools/load_nav.lua"))(nav)
	end
	local edges = ns.Path.BakeRoadEdges(map)
	local keys = {}
	for k in pairs(edges) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	io.stderr:write(("map %d: %d clusters with road edges\n"):format(map, #keys))
	print(("\t[%d] = {"):format(map))
	for _, k in ipairs(keys) do
		print(('\t\t[%d] = "%s",'):format(k + 1, edges[k]))
	end
	print("\t},")
	-- The parent checks for this line: LuaJIT's pipe close does not report a child's exit status.
	print(("-- end of map %d"):format(map))
end

if arg[1] == "--map" then
	BakeMap(assert(tonumber(arg[2]), "--map needs a map id"))
	return
end

-- The interpreter is the lowest arg index, before any of its own flags.
local first = -1
while arg[first - 1] do
	first = first - 1
end
local children = {}
for i, map in ipairs(MAPS) do
	children[i] = assert(io.popen(("'%s' '%s' --map %d"):format(arg[first], arg[0], map)))
end

print("-- Generated by tools/bake_roads.lua; do not edit.")
print("-- Road ratios for each entrance graph edge, per Nav cluster (RoadCells.lua decides which cells are road):")
print('-- edges in entrance order. A run of default edges is "=" and its length in two base64 symbols; any other')
print("-- edge is four symbols: preference and real ratio for walking, then for water walking. A ratio q is")
print("-- 1 + q / 63 * 0.5, so 0 is the road itself and 63 is off it; a default edge is 63 and 0 in both modes.")
print("local ns = select(2, ...)")
print("")
print("-- stylua: ignore")
print("ns.RoadEdges = {")
for i, map in ipairs(MAPS) do
	local out = children[i]:read("*a")
	children[i]:close()
	local body, finished = out:match("^(.*)%-%- end of map (%d+)\n$")
	assert(tonumber(finished) == map, ("the bake of map %d did not finish"):format(map))
	io.write(body)
end
print("}")
