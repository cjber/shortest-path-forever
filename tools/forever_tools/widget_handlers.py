"""Refuse a widget's own client method that takes parameters passed straight as a script handler.

`edit:SetScript("OnEditFocusGained", edit.HighlightText)` hands the client's `HighlightText` method to the client as
the handler. The client calls a handler with the handler's own arguments, so `HighlightText` reads the first one as
its `start` parameter and raises. The mistake broke four addons (cjber/forever-core#269) and SkillUp Forever's
shopping list (cjber/skillup-forever#622): wrap it as `function(self) self:HighlightText() end`.

A method that declares no parameters reads none of the handler's arguments, so it is correct as it stands:
`frame:SetScript("OnDragStop", frame.StopMovingOrSizing)` and `edit:SetScript("OnEscapePressed", edit.ClearFocus)`
both ignore them. `StartMoving(alwaysStartFromMouse)` does take one and reads OnDragStart's button string as it, so
it stays flagged.

A finding is a `SetScript` or `HookScript` whose handler is exactly a field read, `Y.Name` or `Y["Name"]`, where
`Name` is a method that takes parameters and the client's API annotations declare on a widget class.
`widget_methods.txt` carries that set, generated by `tools/gen_widget_methods.py` from the Ketho/vscode-wow-api
checkout `tools/typecheck.sh` pins. A name some scanned file defines as a function is the addon's own method, so it
is not a widget method and passes.
"""

import re
import xml.etree.ElementTree as ET
from collections.abc import Collection, Iterable, Mapping
from functools import lru_cache
from pathlib import Path

from . import toc
from .lua import LuaSyntaxError, Token, tokenize

__all__ = ["annotation_methods", "check", "check_root", "methods", "render"]

DATA = Path(__file__).resolve().parent
METHODS = "widget_methods.txt"
ANNOTATIONS = "Annotations/Core/Widget"
SCRIPTS = frozenset({"SetScript", "HookScript"})
DECLARATION = re.compile(r"^\s*function\s+[A-Za-z_]\w*:([A-Za-z_]\w*)\s*\(([^)]*)\)", re.MULTILINE)
OPENERS = {"(": ")", "{": "}", "[": "]"}
CLOSERS = frozenset(OPENERS.values())


@lru_cache(maxsize=1)
def methods() -> frozenset[str]:
    """Every widget method that takes parameters in the generated data."""
    lines = (DATA / METHODS).read_text(encoding="utf-8").splitlines()
    return frozenset(line for line in lines if line and not line.startswith("#"))


def annotation_methods(directory: Path) -> list[str]:
    """Every method the annotations under `directory` declare with a parameter on a widget class, sorted and unique.

    A method declared on several classes is included when any declaration takes parameters: the receiver's class is
    unknown statically, and only a method that reads none of them is safe as a bare handler."""
    names: set[str] = set()
    for path in sorted(directory.rglob("*.lua")):
        for name, parameters in DECLARATION.findall(path.read_text(encoding="utf-8", errors="replace")):
            if parameters.strip():
                names.add(name)
    return sorted(names)


def render(names: Iterable[str], revision: str) -> str:
    """The data file's text: its source revision and generator, then one method name per line."""
    lines = [
        "# Widget methods that take parameters, from the client's API annotations (Ketho/vscode-wow-api).",
        f"# Annotations/Core/Widget/** at revision {revision}.",
        "# Each line is a method the annotations declare on a widget class with at least one parameter",
        "# (function Widget:Method(parameter)), so the client's handler arguments reach a parameter.",
        "# Generated by tools/gen_widget_methods.py; do not edit by hand.",
        "",
        *names,
    ]
    return "\n".join(lines) + "\n"


def _is(token: Token, text: str) -> bool:
    return token.kind in ("symbol", "keyword") and token.text == text


def _matching(tokens: list[Token], opening: int) -> int:
    """The index of the closer matching the bracket that opens at `opening`."""
    closing, depth = OPENERS[tokens[opening].text], 0
    for at in range(opening, len(tokens)):
        if tokens[at].kind != "symbol":
            continue
        if tokens[at].text == tokens[opening].text:
            depth += 1
        elif tokens[at].text == closing:
            depth -= 1
            if not depth:
                return at
    return len(tokens) - 1


def _arguments(tokens: list[Token], opening: int) -> list[list[Token]]:
    """The tokens of each argument in the call whose `(` is at `opening`, nested brackets kept whole."""
    close = _matching(tokens, opening)
    args: list[list[Token]] = []
    start = opening + 1
    depth = 0
    for at in range(opening + 1, close):
        token = tokens[at]
        if token.kind == "symbol" and token.text in OPENERS:
            depth += 1
        elif token.kind == "symbol" and token.text in CLOSERS:
            depth -= 1
        elif depth == 0 and _is(token, ","):
            args.append(tokens[start:at])
            start = at + 1
    args.append(tokens[start:close])
    return args


def _prefix(tokens: list[Token]) -> bool:
    """Whether `tokens` is one Lua prefix expression: a name, call or index chain with no operator in it."""
    if not tokens:
        return False
    at = 0
    if tokens[at].kind in ("name", "string"):
        at += 1
    elif _is(tokens[at], "("):
        at = _matching(tokens, at) + 1
    else:
        return False
    while at < len(tokens):
        token = tokens[at]
        if _is(token, ".") and at + 1 < len(tokens) and tokens[at + 1].kind == "name":
            at += 2
        elif _is(token, "["):
            at = _matching(tokens, at) + 1
        elif _is(token, ":"):
            at += 2
            if at >= len(tokens):
                return False
            if _is(tokens[at], "(") or _is(tokens[at], "{"):
                at = _matching(tokens, at) + 1
            elif tokens[at].kind == "string":
                at += 1
            else:
                return False
        elif _is(token, "(") or _is(token, "{"):
            at = _matching(tokens, at) + 1
        elif token.kind == "string":
            at += 1
        else:
            return False
    return True


def _field(tokens: list[Token]) -> str | None:
    """The name when `tokens` is exactly a field read `Y.Name` or `Y["Name"]`, else None."""
    if len(tokens) >= 3 and tokens[-1].kind == "name" and _is(tokens[-2], "."):
        receiver, name = tokens[:-2], tokens[-1].text
    elif len(tokens) >= 4 and _is(tokens[-1], "]") and tokens[-2].kind == "string" and _is(tokens[-3], "["):
        receiver, name = tokens[:-3], tokens[-2].text[1:-1]
    else:
        return None
    return name if _prefix(receiver) else None


def _defined(tokens: list[Token]) -> set[str]:
    """Every function name the file defines: `function T:Name(`, `function T.Name(`, `T.Name = function`."""
    names: set[str] = set()
    for at, token in enumerate(tokens):
        if _is(token, "function"):
            cursor = at + 1
            if cursor >= len(tokens) or tokens[cursor].kind != "name":
                continue
            name = tokens[cursor].text
            cursor += 1
            field = False
            while cursor < len(tokens):
                if _is(tokens[cursor], ".") or _is(tokens[cursor], ":"):
                    if cursor + 1 >= len(tokens) or tokens[cursor + 1].kind != "name":
                        break
                    name = tokens[cursor + 1].text
                    field = True
                    cursor += 2
                elif (
                    _is(tokens[cursor], "[")
                    and cursor + 2 < len(tokens)
                    and tokens[cursor + 1].kind == "string"
                    and _is(tokens[cursor + 2], "]")
                ):
                    name = tokens[cursor + 1].text[1:-1]
                    field = True
                    cursor += 3
                else:
                    break
            if field and cursor < len(tokens) and _is(tokens[cursor], "("):
                names.add(name)
        elif token.kind == "name":
            if (
                at + 4 < len(tokens)
                and _is(tokens[at + 1], ".")
                and tokens[at + 2].kind == "name"
                and _is(tokens[at + 3], "=")
                and _is(tokens[at + 4], "function")
            ):
                names.add(tokens[at + 2].text)
            elif (
                at + 5 < len(tokens)
                and _is(tokens[at + 1], "[")
                and tokens[at + 2].kind == "string"
                and _is(tokens[at + 3], "]")
                and _is(tokens[at + 4], "=")
                and _is(tokens[at + 5], "function")
            ):
                names.add(tokens[at + 2].text[1:-1])
    return names


def check(sources: Mapping[str, str]) -> list[str]:
    """Every finding in `sources` (display path to Lua source) as one line, in source order.

    A file that does not tokenise is skipped: the package check reports its syntax error itself.
    """
    known = methods()
    parsed: list[tuple[str, list[Token]]] = []
    for path, source in sources.items():
        try:
            parsed.append((path, tokenize(source)[0]))
        except LuaSyntaxError:
            continue
    defined: set[str] = set()
    for _, tokens in parsed:
        defined.update(_defined(tokens))
    findings: list[str] = []
    for path, tokens in parsed:
        for at, token in enumerate(tokens):
            if not _is(token, ":") or at + 2 >= len(tokens):
                continue
            name = tokens[at + 1].text
            if name not in SCRIPTS or not _is(tokens[at + 2], "("):
                continue
            args = _arguments(tokens, at + 2)
            if len(args) < 2:
                continue
            field = _field(args[1])
            if field is None or field not in known or field in defined:
                continue
            findings.append(
                f"{path}:{token.line}: {field} passed straight as a {name} handler is called with the handler's "
                f"arguments; wrap it: function(self) self:{field}() end"
            )
    return findings


def check_root(root: Path, addons: Collection[str] = ()) -> list[str]:
    """Every finding in the Lua `root`'s TOCs and their XML load, paths relative to `root`.

    `addons` names the packaged addon folders to read (`Policy.addons`), so a bundled ForeverCore is not linted as
    the consumer's own code; without it, `root`'s own TOCs are read. A missing file is skipped, because the package
    check names it itself."""
    root = root.resolve()
    sources: dict[str, str] = {}
    for folder in (root / addon for addon in addons) if addons else (root,):
        for toc_path in sorted(folder.glob("*.toc")):
            try:
                files = toc.loaded_files(toc_path, folder)
            except (OSError, ValueError, ET.ParseError):
                continue
            for path in files:
                if path.suffix.lower() != ".lua":
                    continue
                try:
                    sources[path.relative_to(root).as_posix()] = path.read_text(encoding="utf-8")
                except (OSError, ValueError, UnicodeDecodeError):
                    continue
    return check(sources)
