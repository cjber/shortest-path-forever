"""Refuse a call of a client function the Forever client does not answer.

`attempt to call a nil value` is the error this lint exists for, and a call is the one place it happens. LuaLS checks
every name against the retail `vscode-wow-api` annotations, and this repository's `types/` files only add to them, so a
retail-only function (`C_Retail.Foo`, `SomeRetailGlobal`) type-checks and then fails in game. This lint checks the
names against the Forever client itself: `forever_tools/client_names.txt`, generated by `tools/gen_forever_api.py` from
the pinned Blizzard UI source and an optional ForeverProbe dump.

- `client-missing`: a bare global called as a function, `Name(...)` (or `Name{...}`, `Name"text"`), when the name is
  neither in `client_names.txt`, a Lua 5.1 or WoW global the pinned annotations define, nor a global the addon itself,
  the pinned ForeverCore checkout or the addon's `tools/client_optional.txt` declares. Defined means assigned
  (`Name = ...`, `function Name(...)`, `_G.Name = ...`), created by `CreateFrame(type, "Name")`, named by a ForeverCore
  helper that takes the frame's name (`ForeverCore.TrackerSection.Create("Name", ...)` and the two `spec.name`
  helpers), named in XML (`name="Name"`), listed in a TOC's `## SavedVariables`, or declared for an optional dependency.
  Every other use of a bare global is a read, not a call: `Name:Method(...)` makes `Name` a table, and a plain read of
  a string, table or constant is neither, so neither raises `attempt to call a nil value` and neither is checked.
- `client-missing`: any read of `C_X.Y`, called or not, that is not in `client_names.txt`.
- `client-optional-folder`: a `tools/client_optional.txt` line names an addon folder the root TOC's `## OptionalDeps`
  does not list.
- `client-optional-unused`: a declared name the addon never calls.
- `client-waiver-unused`: a `client-ok` waiver that excuses nothing.

An exception carries `-- client-ok: <reason>` on its line or the line above.
"""

