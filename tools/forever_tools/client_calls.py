def _tokens(source: str) -> list[Token]:
    return tokenize(source.lstrip("\ufeff"))[0]


def _matching(tokens: list[Token], index: int) -> int:
    """The index of the bracket closing the one at `index`."""
    opening = tokens[index].text
    closing = CLOSING[opening]
    depth = 0
    for cursor in range(index, len(tokens)):
        depth += tokens[cursor].text == opening
        depth -= tokens[cursor].text == closing
        if depth == 0:
            return cursor
    raise LuaSyntaxError(f"{tokens[index].line}: unclosed {opening}")


def _header_dos(tokens: list[Token]) -> set[int]:
    """The `do` that opens each `for` and `while` body, so it is not counted as a block of its own."""
    found: set[int] = set()
    for index, token in enumerate(tokens):
        if token.text not in {"for", "while"}:
            continue
        depth = 0
        for cursor in range(index + 1, len(tokens)):
            text = tokens[cursor].text
            if text in CLOSING:
                depth += 1
            elif text in {"}", ")", "]"}:
                depth -= 1
            elif text == "do" and depth == 0:
                found.add(cursor)
                break
    return found


def _blocks(tokens: list[Token], dos: set[int]) -> dict[int, int]:
    """Each block opener's closer: `end`, or `until` for `repeat`."""
    ends: dict[int, int] = {}
    stack: list[tuple[int, str]] = []
    for index, token in enumerate(tokens):
        if token.kind != "keyword":
            continue
        word = token.text
        if word in {"function", "if", "for", "while", "repeat"} or (word == "do" and index not in dos):
            stack.append((index, "until" if word == "repeat" else "end"))
        elif word in {"end", "until"}:
            if not stack or stack[-1][1] != word:
                raise LuaSyntaxError(f"{token.line}: unmatched {word}")
            opener, _ = stack.pop()
            ends[opener] = index
    if stack:
        raise LuaSyntaxError(f"{tokens[stack[-1][0]].line}: unclosed block")
    return ends


def _enclosing(tokens: list[Token], ends: dict[int, int]) -> list[int]:
    """For each token, the closer of the innermost block that contains it."""
    found = [len(tokens) - 1] * len(tokens)
    stack: list[int] = []
    for index, token in enumerate(tokens):
        if token.kind == "keyword" and token.text in {"end", "until"}:
            found[index] = stack[-1] if stack else len(tokens) - 1
            if stack:
                stack.pop()
            continue
        found[index] = stack[-1] if stack else len(tokens) - 1
        if index in ends:
            stack.append(ends[index])
    return found


def _suffixed(tokens: list[Token], index: int, ends: dict[int, int]) -> int:
    """The index after a primary expression and its suffix chain."""
    token = tokens[index]
    if token.text == "function":
        return ends[index] + 1
    if token.text in {"{", "("}:
        cursor = _matching(tokens, index) + 1
    elif token.kind in {"name", "number", "string"} or token.text in {"true", "false", "nil", "..."}:
        cursor = index + 1
    else:
        return index
    while True:
        text = tokens[cursor].text
        if text in {".", ":"} and tokens[cursor + 1].kind == "name":
            cursor += 2
        elif text in {"(", "["}:
            cursor = _matching(tokens, cursor) + 1
        elif tokens[cursor].kind == "string":
            cursor += 1
        else:
            return cursor


def _unary(tokens: list[Token], index: int, ends: dict[int, int]) -> int:
    if tokens[index].text in UNARY:
        return _unary(tokens, index + 1, ends)
    return _suffixed(tokens, index, ends)


def _expression(tokens: list[Token], index: int, ends: dict[int, int]) -> int:
    cursor = _unary(tokens, index, ends)
    while tokens[cursor].text in BINARY:
        cursor = _unary(tokens, cursor + 1, ends)
    return cursor


def _expressions(tokens: list[Token], index: int, ends: dict[int, int]) -> int:
    cursor = _expression(tokens, index, ends)
    while tokens[cursor].text == ",":
        cursor = _expression(tokens, cursor + 1, ends)
    return cursor


def _declarations(
    tokens: list[Token], ends: dict[int, int], enclosing: list[int]
) -> tuple[dict[str, list[tuple[int, int]]], set[int]]:
    """Each local's scope as (first index in scope, last index), and every declaration's own name token."""
    scopes: dict[str, list[tuple[int, int]]] = {}
    declared: set[int] = set()

    def add(name: str, start: int, end: int) -> None:
        scopes.setdefault(name, []).append((start, end))

    for index, token in enumerate(tokens):
        if token.text == "local" and token.kind == "keyword":
            if tokens[index + 1].text == "function":
                declared.add(index + 2)
                add(tokens[index + 2].text, index + 3, enclosing[index])
                continue
            cursor, names = index + 1, []
            while tokens[cursor].kind == "name":
                names.append((tokens[cursor].text, cursor))
                declared.add(cursor)
                cursor += 1
                if tokens[cursor].text != ",":
                    break
                cursor += 1
            if not names:
                continue
            start = _expressions(tokens, cursor + 1, ends) if tokens[cursor].text == "=" else cursor
            for name, _ in names:
                add(name, start, enclosing[index])
        elif token.text == "for" and token.kind == "keyword":
            cursor, names = index + 1, []
            while tokens[cursor].kind == "name":
                names.append((tokens[cursor].text, cursor))
                declared.add(cursor)
                cursor += 1
                if tokens[cursor].text != ",":
                    break
                cursor += 1
            while tokens[cursor].text not in {"=", "in", "do"}:
                cursor += 1
            while tokens[cursor].text != "do":
                cursor += 1
            for name, _ in names:
                add(name, cursor + 1, ends[index])
        elif token.text == "function" and token.kind == "keyword":
            cursor = index + 1
            method = False
            while tokens[cursor].kind == "name" and tokens[cursor + 1].text in {".", ":"}:
                method = method or tokens[cursor + 1].text == ":"
                cursor += 2
            if tokens[cursor].kind == "name":
                cursor += 1
            if tokens[cursor].text != "(":
                continue
            if method:
                add("self", cursor + 1, ends[index])
            cursor += 1
            while tokens[cursor].text != ")":
                if tokens[cursor].kind == "name":
                    declared.add(cursor)
                    add(tokens[cursor].text, cursor + 1, ends[index])
                cursor += 1
    return scopes, declared


def _contexts(tokens: list[Token], dos: set[int]) -> list[str]:
    """For each token, the constructor it sits in: `table`, `paren`, `function`, `block` or `top`."""
    found = ["top"] * len(tokens)
    stack: list[str] = []
    for index, token in enumerate(tokens):
        word = token.text
        if word == "{":
            kind = "table"
        elif word in {"(", "["}:
            kind = "paren"
        elif word == "function":
            kind = "function"
        elif word in {"if", "for", "while", "do", "repeat"} and index not in dos:
            kind = "block"
        else:
            kind = ""
        if kind:
            found[index] = stack[-1] if stack else "top"
            stack.append(kind)
        elif word in {"}", ")", "]", "end", "until"}:
            if stack:
                stack.pop()
            found[index] = stack[-1] if stack else "top"
        else:
            found[index] = stack[-1] if stack else "top"
    return found


def _local(name: str, index: int, scopes: dict[str, list[tuple[int, int]]]) -> bool:
    return any(start <= index <= end for start, end in scopes.get(name, ()))


def _assignment_target(tokens: list[Token], index: int) -> bool:
    """Whether the name at `index` is in the target list of `a, b = ...`."""
    cursor = index + 1
    while tokens[cursor].text == "," and tokens[cursor + 1].kind == "name":
        cursor += 2
    return tokens[cursor].text == "="


def _arguments(tokens: list[Token], open_index: int) -> list[list[Token]]:
    """The arguments of the call whose `(` is at `open_index`, each as its own tokens."""
    end = _matching(tokens, open_index)
    arguments, depth, start = [], 0, open_index + 1
    for cursor in range(open_index + 1, end):
        text = tokens[cursor].text
        if text in CLOSING:
            depth += 1
        elif text in {"}", ")", "]"}:
            depth -= 1
        elif text == "," and depth == 0:
            arguments.append(tokens[start:cursor])
            start = cursor + 1
    arguments.append(tokens[start:end])
    return arguments


def _literal(argument: list[Token]) -> str | None:
    """The string a single-token argument holds, or None."""
    if len(argument) == 1 and argument[0].kind == "string":
        return unescape(argument[0].text)
    return None


def _field(argument: list[Token], name: str) -> str | None:
    """The string a `{ name = "X", ... }` table constructor gives its `name` field, or None."""
    if len(argument) < 2 or argument[0].text != "{":
        return None
    depth = 0
    for cursor, token in enumerate(argument):
        if token.text in CLOSING:
            depth += 1
        elif token.text in {"}", ")", "]"}:
            depth -= 1
        elif (
            depth == 1
            and token.kind == "name"
            and token.text == name
            and argument[cursor + 1].text == "="
            and argument[cursor - 1].text in {"{", ",", ";"}
        ):
            value = argument[cursor + 2 : cursor + 3]
            return _literal(value)
    return None


def _created_frames(tokens: list[Token], index: int) -> list[str]:
    """The names `CreateFrame(type, "Name", ...)` creates at this call."""
    if tokens[index].text != "CreateFrame" or tokens[index + 1].text != "(":
        return []
    arguments = _arguments(tokens, index + 1)
    if len(arguments) < 2:
        return []
    name = _literal(arguments[1])
    return [name] if name is not None else []


def _named_by_helper(tokens: list[Token], index: int) -> list[str]:
    """The global frame a call to one of `NAMING_HELPERS` names at this token, or nothing."""
    for helper in NAMING_HELPERS:
        cursor = index
        for part in helper.path[1:]:
            if tokens[cursor + 1].text != "." or tokens[cursor + 2].text != part:
                break
            cursor += 2
        else:
            if tokens[cursor + 1].text != "(":
                continue
            arguments = _arguments(tokens, cursor + 1)
            if len(arguments) <= helper.argument:
                continue
            argument = arguments[helper.argument]
            name = _literal(argument) if helper.field is None else _field(argument, helper.field)
            return [name] if name is not None else []
    return []


def analysis(source: str) -> Analysis:
    """What `source` defines globally, which of those are functions, and which global names it reads; malformed Lua
    raises LuaSyntaxError."""
    tokens = _tokens(source)
    dos = _header_dos(tokens)
    ends = _blocks(tokens, dos)
    enclosing = _enclosing(tokens, ends)
    scopes, declared = _declarations(tokens, ends, enclosing)
    contexts = _contexts(tokens, dos)
    definitions: set[str] = set()
    functions: set[str] = set()
    reads: list[Read] = []
    for index, token in enumerate(tokens):
        if token.kind != "name":
            continue
        name = token.text
        previous = tokens[index - 1].text if index else ""
        following = tokens[index + 1].text
        field = previous in {".", ":"}
        key = following == "=" and contexts[index] == "table" and previous in {"{", ",", ";"}
        local = index in declared or _local(name, index, scopes)
        target = not field and not key and not local and _assignment_target(tokens, index)
        if name == "_G" and following in {".", "["}:
            if following == "." and tokens[index + 2].kind == "name" and tokens[index + 3].text == "=":
                definitions.add(tokens[index + 2].text)
                if tokens[index + 4].text == "function":
                    functions.add(tokens[index + 2].text)
            elif (
                following == "["
                and tokens[index + 2].kind == "string"
                and tokens[index + 3].text == "]"
                and tokens[index + 4].text == "="
            ):
                definitions.add(unescape(tokens[index + 2].text))
                if tokens[index + 5].text == "function":
                    functions.add(unescape(tokens[index + 2].text))
        if not field and not key and not local:
            if target:
                definitions.add(name)
                if following == "=" and tokens[index + 2].text == "function":
                    functions.add(name)
            elif previous == "function" and following == "(" and not (index >= 2 and tokens[index - 2].text == "local"):
                definitions.add(name)
                functions.add(name)
        if not field:
            definitions.update(_created_frames(tokens, index))
            definitions.update(_named_by_helper(tokens, index))
        if field or key or local or target or (previous == "function" and following == "("):
            continue
        call = following in {"(", "{"} or tokens[index + 1].kind == "string"
        if name.startswith("C_") and len(name) > 2:
            if following == "." and tokens[index + 2].kind == "name":
                after = tokens[index + 3]
                if not (after.text == "=" and contexts[index + 3] != "table"):
                    field_call = after.text in {"(", "{"} or after.kind == "string"
                    reads.append(Read(token.line, qualified=f"{name}.{tokens[index + 2].text}", call=field_call))
                continue
            if (
                following == "["
                and tokens[index + 2].kind == "string"
                and tokens[index + 3].text == "]"
                and tokens[index + 4].text != "="
            ):
                after = tokens[index + 4]
                field_call = after.text in {"(", "{"} or after.kind == "string"
                reads.append(Read(token.line, qualified=f"{name}.{unescape(tokens[index + 2].text)}", call=field_call))
                continue
            reads.append(Read(token.line, name=name, call=call))
            continue
        reads.append(Read(token.line, name=name, call=call))
    return Analysis(frozenset(definitions), tuple(reads), frozenset(functions))


def definitions(source: str) -> frozenset[str]:
    """Every global one Lua source defines: an assignment, a multi-assignment target, a function declaration, a
    `CreateFrame(type, "Name")` frame or a global frame named by a ForeverCore helper. XML names and TOC saved
    variables are `xml_definitions` and `saved_variables`."""
    return analysis(source).definitions


def xml_definitions(paths: list[Path]) -> frozenset[str]:
    """Every global an XML file creates with `name="X"`: a virtual frame or region is a template, not a global, while
    a virtual `Font` or `FontFamily` is still the global Blizzard's own Lua sets on frames (`GameFontNormal`)."""
    names: set[str] = set()
    for path in paths:
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError as error:
            raise ValueError(f"{path}: {error}") from error
        for element in root.iter():
            name = element.attrib.get("name")
            tag = element.tag.rsplit("}", 1)[-1]
            virtual = element.attrib.get("virtual", "").lower() == "true" and tag not in {"Font", "FontFamily"}
            if name and "$" not in name and not virtual:
                names.add(name)
    return frozenset(names)


def saved_variables(toc_paths: list[Path]) -> frozenset[str]:
    """Every global a TOC's `## SavedVariables` or `## SavedVariablesPerCharacter` declares."""
    names: set[str] = set()
    for path in toc_paths:
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            match = SAVED.match(line.strip())
            if match:
                names.update(part.strip() for part in match.group(1).split(",") if part.strip())
    return frozenset(names)


def optional_deps(toc_paths: list[Path]) -> frozenset[str]:
    """Every addon folder a TOC's `## OptionalDeps` lists."""
    names: set[str] = set()
    for path in toc_paths:
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            match = OPTIONAL.match(line.strip())
            if match:
                names.update(part.strip() for part in match.group(1).split(",") if part.strip())
    return frozenset(names)


def root_tocs(root: Path) -> list[Path]:
    """The addon's own TOCs: the ones at the checkout's root, never a nested addon's."""
    return sorted(root.glob("*.toc"))


def declarations(path: Path) -> tuple[list[Declaration], list[tuple[int, str]]]:
    """The declarations a `tools/client_optional.txt` holds, and one finding per line that is not
    `Name  OwningAddonFolder`. A missing file declares nothing."""
    if not path.is_file():
        return [], []
    found: list[Declaration] = []
    problems: list[tuple[int, str]] = []
    for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        text = line.split("#", 1)[0].strip()
        if not text:
            continue
        match = DECLARATION.match(text)
        if match is None:
            problems.append((number, "client-optional-format: expected `Name  OwningAddonFolder`"))
            continue
        found.append(Declaration(match.group(1), match.group(2), number))
    return found, problems


def load_names(path: Path = NAMES_FILE) -> frozenset[str]:
    """The names in a generated `client_names.txt`, one per line, `#` comments skipped."""
    return frozenset(
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    )


def lua_globals(annotations: Path) -> frozenset[str]:
    """Lua 5.1 and WoW extension globals as the pinned annotations define them: `Annotations/Core/Lua` and the
    `Enum` and `Constants` tables in `Annotations/Core/Data/Enum.lua`.

    The annotations declare `os.date`, `os.time` and `os.difftime` as globals with "no namespace" and have no file
    for the `coroutine` and `debug` libraries, so those three standard Lua 5.1 library tables (the Lua 5.1 manual's
    section 5) are added; the WoW client provides them (`forever_sim/client.lua`). `package` is not: the client's
    Lua 5.1 has it removed.
    """
    files = sorted((annotations / "Annotations" / "Core" / "Lua").glob("*.lua"))
    files.append(annotations / "Annotations" / "Core" / "Data" / "Enum.lua")
    names: set[str] = {"coroutine", "debug", "os"}
    for path in files:
        if path.is_file():
            names.update(definitions(path.read_text(encoding="utf-8")))
    return frozenset(names)


def _folder_definitions(root: Path) -> tuple[list[Path], frozenset[str]]:
    """The runtime Lua files under `root` and every global they, their XML or their TOCs define."""
    tocs = toc.toc_files(root)
    files: set[Path] = set()
    for toc_path in tocs:
        files.update(toc.loaded_files(toc_path, root))
    defined: set[str] = set()
    for path in sorted(files):
        if path.suffix.lower() == ".lua":
            defined.update(definitions(path.read_text(encoding="utf-8", errors="replace")))
    defined.update(xml_definitions([path for path in sorted(files) if path.suffix.lower() == ".xml"]))
    defined.update(saved_variables(tocs))
    return [path for path in sorted(files) if path.suffix.lower() == ".lua"], frozenset(defined)


def environment(
    root: Path, annotations: Path, api: Path = NAMES_FILE, core: Path | None = None
) -> tuple[list[Path], Environment]:
    """The runtime Lua files to check under `root`, and the names they may read.

    `annotations` is the pinned vscode-wow-api checkout (for the Lua and WoW globals); `core` is the ForeverCore
    checkout whose runtime files define the globals an addon reads from it. `root/tools/client_optional.txt` declares
    the global functions an optional dependency provides.
    """
    paths, defined = _folder_definitions(root.resolve())
    names = set(defined)
    if core is not None and core.resolve() != root.resolve():
        _, core_defined = _folder_definitions(core.resolve())
        names.update(core_defined)
    declared, _ = declarations(root.resolve() / DECLARATIONS)
    return paths, Environment(
        api=load_names(api),
        globals=lua_globals(annotations),
        defined=frozenset(names),
        optional=frozenset(declaration.name for declaration in declared),
    )


def _analysed(source: str) -> Analysis:
    """`source` analysed, with an unexpected end of file reported as the syntax error it is."""
    try:
        return analysis(source)
    except IndexError as error:
        raise LuaSyntaxError("unexpected end of file") from error


def _findings(source: str, environment: Environment) -> list[tuple[int, str]]:
    """`(line, message)` for each call of a name the client does not answer in `source`."""
    result = _analysed(source)
    lines = source.splitlines()
    known = environment.api | environment.globals | environment.defined | environment.optional | result.definitions
    raw: list[tuple[int, str]] = []
    for read in result.reads:
        if read.qualified is not None:
            if read.qualified not in environment.api:
                raw.append(
                    (
                        read.line,
                        f"client-missing: {read.qualified} is not in the Forever client's API ({NAMES_FILE.name})",
                    )
                )
        elif read.name is not None and read.call:
            if read.name in known:
                continue
            raw.append(
                (
                    read.line,
                    f"client-missing: {read.name} is not defined by the Forever client, this addon or ForeverCore",
                )
            )
    found, excused = [], set()
    for number, message in sorted(set(raw)):
        waiver = next(
            (at for at in (number, number - 1) if at >= 1 and at <= len(lines) and WAIVER.search(lines[at - 1])), None
        )
        if waiver is None:
            found.append((number, message))
        else:
            excused.add(waiver)
    for number, line in enumerate(lines, 1):
        if MARK.search(line) and number not in excused:
            reason = "names no reason" if not WAIVER.search(line) else "excuses no missing client call"
            found.append((number, f"client-waiver-unused: this client-ok {reason}"))
    return sorted(found)


def check(source: str, environment: Environment = DEFAULT_ENVIRONMENT) -> list[tuple[int, str]]:
    """`(line, message)` for each call of a name the client does not answer in one source; malformed Lua raises
    LuaSyntaxError."""
    return _findings(source, environment)


def findings(
    root: Path, paths: list[Path], environment: Environment = DEFAULT_ENVIRONMENT
) -> list[tuple[Path, int, str]]:
    """Every finding for an addon: one per runtime file, then its `tools/client_optional.txt`."""
    found: list[tuple[Path, int, str]] = []
    called: set[str] = set()
    for path in paths:
        source = path.read_text(encoding="utf-8", errors="replace")
        result = _analysed(source)
        called.update(read.name for read in result.reads if read.name is not None and read.call)
        found.extend((path, line, message) for line, message in _findings(source, environment))
    declared, problems = declarations(root / DECLARATIONS)
    found.extend((root / DECLARATIONS, line, message) for line, message in problems)
    allowed = optional_deps(root_tocs(root))
    for declaration in declared:
        if declaration.folder not in allowed:
            found.append(
                (
                    root / DECLARATIONS,
                    declaration.line,
                    f"client-optional-folder: {declaration.folder} is not in the root TOC's ## OptionalDeps",
                )
            )
        if declaration.name not in called:
            found.append(
                (
                    root / DECLARATIONS,
                    declaration.line,
                    f"client-optional-unused: {declaration.name} is declared but never called",
                )
            )
    return found


def run(root: Path, paths: list[Path], environment: Environment = DEFAULT_ENVIRONMENT) -> int:
    """Print every finding for one addon; true as an exit code when any is left."""
    try:
        found = findings(root, paths, environment)
    except (LuaSyntaxError, OSError, UnicodeDecodeError) as error:
        print(f"{root}: {error}", file=sys.stderr)
        return 1
    for path, line, message in found:
        print(f"{path}:{line}: {message}")
    if not found:
        print(f"Client calls: {len(paths)} files checked, {len(environment.api)} client names")
    return int(bool(found))
