#!/usr/bin/env python3
"""Generate Data/ZoneCells.lua: the zone map the client names for every 64-yard square of the two continents.

Journey/Hazards.lua asks which zone a square is in, at the square's centre, through C_Map: several calls a square, and
a first journey's plan asks for about 20000 squares. The client's own answers ship instead. They come from a dump the
in-game check makes with tools/zone_cells_dump.lua (one "Z<map> <column> <first row> <zone>x<count> ..." line per
column, zone 0 for none), which this turns into one run-length string per column.

    python3 tools/gen_zone_cells.py DUMP
"""

import argparse
import sys
from pathlib import Path

try:
    from tools.forever_tools.fsio import atomic_write
except ModuleNotFoundError:
    from forever_tools.fsio import atomic_write

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "Data" / "ZoneCells.lua"


def parse(text):
    """{map: {column: (first row, [(zone, count), ...])}} from the dump's lines; other lines are ignored."""
    maps = {}
    for line in text.splitlines():
        if not line.startswith("Z"):
            continue
        head, column, first, *runs = line.split()
        cells = maps.setdefault(int(head[1:]), {})
        cells[int(column)] = (int(first), [tuple(int(part) for part in run.split("x")) for run in runs])
    return maps


def render(maps):
    """The Lua data file for parsed columns: every column of a map starts at the same row."""
    lines = [
        "-- Generated by tools/gen_zone_cells.py from the client's C_Map answers; do not edit.",
        "-- [map] = { i0, j0, columns }: column i0 + k - 1 is runs of zone and count from row j0 up, in 64-yard",
        "-- squares (math.floor(x / 64), math.floor(y / 64)); zone 0 is none.",
        "---@type string, SPFNamespace",
        "local _, ns = ...",
        "",
        "-- stylua: ignore",
        "ns.ZoneCells = {",
    ]
    for map_id in sorted(maps):
        columns = maps[map_id]
        first = min(columns)
        rows = {row for row, _ in columns.values()}
        if len(rows) != 1 or sorted(columns) != list(range(first, first + len(columns))):
            raise SystemExit(f"map {map_id}: columns must be contiguous and start at one row")
        lines.append(f"\t[{map_id}] = {{ i0 = {first}, j0 = {rows.pop()}, columns = {{")
        for column in sorted(columns):
            runs = " ".join(f"{zone} {count}" for zone, count in columns[column][1])
            lines.append(f'\t\t"{runs}",')
        lines.append("\t} },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dump", type=Path)
    args = parser.parse_args(argv)
    maps = parse(args.dump.read_text())
    if not maps:
        raise SystemExit(f"{args.dump}: no zone cell lines")
    atomic_write(OUTPUT, render(maps))
    return 0


if __name__ == "__main__":
    sys.exit(main())
