-- Reads Blizzard_APIDocumentationGenerated: every system (C_* namespaces and global functions), every widget API
-- (ScriptObject systems), enumerations, constants and events, with the client's secret and protection flags.
-- Function tables keep the documented flags whole, including IsProtectedFunction and HasRestrictions.
local M = {}

local here = debug.getinfo(1, "S").source:match("^@(.*[/\\])") or "./"
local restrictions

local function readFile(path)
	local f = io.open(path, "rb")
	if not f then
		return nil
	end
	local text = f:read("*a")
	f:close()
	return text
end
M.readFile = readFile

-- Returns { systems = {...}, widgets = { [systemName] = system }, enums = {...}, constants = {...},
-- structures = { [name] = table }, events = { [LiteralName] = event } }.
function M.load(uiRoot)
	local dir = uiRoot .. "/Interface/AddOns/Blizzard_APIDocumentationGenerated/"
	local toc = readFile(dir .. "Blizzard_APIDocumentationGenerated.toc")
	if not toc then
		error("no API documentation under " .. dir .. " (fetch the UI source first)")
	end
	local out = { systems = {}, widgets = {}, enums = {}, constants = {}, structures = {}, events = {} }
	local sink = {
		AddDocumentationTable = function(_, t)
			if t.Type == "ScriptObject" then
				out.widgets[t.Name] = t
			else
				out.systems[#out.systems + 1] = t
			end
			for _, tbl in ipairs(t.Tables or {}) do
				if tbl.Type == "Enumeration" then
					out.enums[tbl.Name] = tbl
				elseif tbl.Type == "Constants" then
					out.constants[tbl.Name] = tbl
				elseif tbl.Type == "Structure" then
					out.structures[tbl.Name] = tbl
				end
			end
			for _, ev in ipairs(t.Events or {}) do
				out.events[ev.LiteralName] = ev
			end
		end,
	}
	-- The documentation files reference Enum and Constants values in defaults; give them a forgiving lookup.
	local forgivingMeta
	-- A placeholder remembers its path ("SecretAspect.Text") so flags naming enum values can be read back.
	local function forgiving(path)
		return setmetatable({ __name = path }, forgivingMeta)
	end
	local function same(a, b)
		return getmetatable(a) == forgivingMeta and a or b
	end
	forgivingMeta = {
		__index = function(t, k)
			local base = rawget(t, "__name")
			local child = forgiving(base and (base .. "." .. tostring(k)) or tostring(k))
			rawset(t, k, child)
			return child
		end,
		__add = same,
		__sub = same,
		__mul = same,
		__div = same,
		__unm = same,
		__concat = same,
	}
	-- Native macros some constants are documented with (Classic-era values, as the Forever client uses).
	local macros = {
		NUM_BAG_SLOTS = 4,
		NUM_REAGENTBAG_SLOTS = 0,
		NUM_CHARACTERBANK_SLOTS = 6,
		NUM_ACCOUNTBANK_SLOTS = 0,
	}
	local env = setmetatable({ APIDocumentation = sink }, {
		__index = function(_, k)
			if k == "Enum" or k == "Constants" then
				return forgiving(nil)
			end
			if macros[k] then
				return macros[k]
			end
			return _G[k]
		end,
	})
	for line in toc:gmatch("[^\r\n]+") do
		local file = line:match("^%s*([^#%s][^%s]*%.lua)")
		if file then
			local text = readFile(dir .. file:gsub("\\", "/"))
			if text then
				local chunk = assert(loadstring(text, "@Blizzard_APIDocumentationGenerated/" .. file))
				setfenv(chunk, env)
				chunk()
			end
		end
	end
	out.restrictions = M.restrictions
	out.restrictionClasses = M.restrictionClasses
	out.applies = M.applies
	return out
end

-- The enum value names a documentation flag lists ({ Enum.SecretAspect.Text } -> { "Text" }).
function M.enumNames(list)
	local out = {}
	for _, v in ipairs(list or {}) do
		local name = type(v) == "table" and rawget(v, "__name")
		if name then
			out[#out + 1] = name:match("([^.]+)$")
		end
	end
	return out
end

-- The pinned classes of every documented HasRestrictions function and widget method, from restrictions.txt beside
-- this file: name -> { class, ... }. A name can carry several classes, since one wiki tag can name several, and the
-- sim refuses the call when any of them applies. An unmodelled tag and a name with no template are "untagged", which
-- keeps the pre-class combat-only rule. The file is generated by `fetch.py --refresh-restrictions` from the wiki's
-- restrictedapi template and committed, so a spec never depends on the wiki being reachable.
function M.restrictions(path)
	if restrictions == nil then
		restrictions = {}
		local file = io.open(path or (here .. "restrictions.txt"), "r")
		if not file then
			error("no restrictions.txt beside docs.lua: run python3 forever_sim/fetch.py --refresh-restrictions")
		end
		for line in file:lines() do
			local name, classes = line:match("^(%S+)%s+([^%s#]+)%s*$")
			if name and not name:match("^#") then
				local list = {}
				for class in classes:gmatch("[^,]+") do
					list[#list + 1] = class
				end
				restrictions[name] = list
			end
		end
		file:close()
	end
	return restrictions
end

-- The classes of a qualified name, or nil for a name the pin does not list.
function M.restrictionClasses(name)
	return M.restrictions()[name]
end

-- True when any class applies: "always" at any time, "hwevent" without a hardware input, and "nocombat" or an
-- untagged name (the pre-class rule every HasRestrictions name keeps) in combat.
function M.applies(classes, combat, hardwareInput)
	for _, class in ipairs(classes or {}) do
		if class == "always" then
			return true
		elseif class == "hwevent" then
			if not hardwareInput then
				return true
			end
		elseif combat then
			return true
		end
	end
	return false
end

return M
