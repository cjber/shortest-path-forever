#!/usr/bin/env python3
"""Generate Data/SpellTargets.lua: the spells that range-check another unit, split by the units they can be asked
about, and the usable items whose on-use spell does, with that spell's range (stdlib)."""

import argparse

from gen_routes import BUILD, ROOT, db2
from gen_transit import render

try:
    from tools.forever_tools.fsio import publish
except ModuleNotFoundError:
    from forever_tools.fsio import publish

OUTPUT = ROOT / "Data" / "SpellTargets.lua"
# SpellEffect.ImplicitTarget values from the Recast/TrinityCore Targets enum, as SpellInfo.cpp's
# SpellImplicitTargetInfo::_data list names them: 21 TARGET_UNIT_TARGET_ALLY, 25 TARGET_UNIT_TARGET_ANY and
# 45 TARGET_UNIT_TARGET_CHAINHEAL_ALLY are the explicit target rows a friendly NPC can answer. 6
# TARGET_UNIT_TARGET_ENEMY and 25 TARGET_UNIT_TARGET_ANY are the rows a hostile NPC can answer. Caster (1), pet (5)
# and area (7-9, 15, 16) targets are not a range check to the unit the band measured.
FRIENDLY_TARGETS = {21, 25, 45}
HOSTILE_TARGETS = {6, 25}
# ItemEffect.TriggerType: on use. On equip (1) is a worn item's lasting bonus, not a range check.
ON_USE = 0
# SpellMisc has one row per difficulty; 0 is the row every client reads.
NORMAL_DIFFICULTY = 0


def band_spells(spell_effect):
    """The sorted friendly and hostile spell IDs with an effect whose implicit target is another unit."""
    friendly, hostile = set(), set()
    for row in spell_effect:
        if not int(row["Effect"]):
            continue
        targets = {int(row["ImplicitTarget_0"]), int(row["ImplicitTarget_1"])}
        spell = int(row["SpellID"])
        if targets & FRIENDLY_TARGETS:
            friendly.add(spell)
        if targets & HOSTILE_TARGETS:
            hostile.add(spell)
    return sorted(friendly), sorted(hostile)


def band_items(item_x_item_effect, item_effect, spell_misc, spell_range, friendly, hostile):
    """Item ID -> its on-use spell's max range and which units that spell can be asked about."""
    use_spells = {int(row["ID"]): int(row["SpellID"]) for row in item_effect if int(row["TriggerType"]) == ON_USE}
    range_index = {
        int(row["SpellID"]): int(row["RangeIndex"])
        for row in spell_misc
        if int(row["DifficultyID"]) == NORMAL_DIFFICULTY
    }
    max_range = {int(row["ID"]): int(row["RangeMax_0"]) for row in spell_range}
    friendly, hostile = set(friendly), set(hostile)
    items = {}
    for row in item_x_item_effect:
        item = int(row["ItemID"])
        spell = use_spells.get(int(row["ItemEffectID"]))
        if spell is None:
            continue
        can_friendly = spell in friendly
        can_hostile = spell in hostile
        if not (can_friendly or can_hostile):
            continue
        index = range_index.get(spell)
        distance = max_range.get(index) if index is not None else None
        if distance is None:
            continue
        entry = items.setdefault(item, {"range": distance})
        # A use spell with a minimum range still bounds from above by its maximum, so only the maximum is stored.
        entry["range"] = min(entry["range"], distance)
        if can_friendly:
            entry["friendly"] = True
        if can_hostile:
            entry["hostile"] = True
    return dict(sorted(items.items()))


def render_targets(friendly, hostile, items):
    lines = [
        "-- Generated by tools/gen_targets.py - do not edit.",
        "-- Source: SpellEffect.ImplicitTarget for the spells and ItemXItemEffect/ItemEffect/SpellMisc/SpellRange",
        "-- for the items' on-use spell ranges.",
        "-- SpellTargets: spells whose effects target an explicit ally (TARGET_UNIT_TARGET_ALLY, 21, and",
        "-- TARGET_UNIT_TARGET_CHAINHEAL_ALLY, 45) or any explicit unit (TARGET_UNIT_TARGET_ANY, 25); caster, pet,",
        "-- area and enemy-only targets are left out, because Routing/Band.lua asks a friendly NPC only about those.",
        "-- HostileSpells: spells whose effects target an enemy (TARGET_UNIT_TARGET_ENEMY, 6) or any explicit unit",
        "-- (25), the rows a hostile NPC answers. BandItems: [item] = its on-use spell's max range and the units",
        "-- that spell targets; only items the player carries are asked about.",
        f"-- DB2: https://wago.tools/db2 (CSV build {BUILD}).",
        "---@type string, SPFNamespace",
        "local _, ns = ...",
        "",
        "-- stylua: ignore",
        "ns.SpellTargets = " + render({spell: True for spell in friendly}),
        "",
        "-- stylua: ignore",
        "ns.HostileSpells = " + render({spell: True for spell in hostile}),
        "",
        "-- stylua: ignore",
        "ns.BandItems = " + render(items),
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--refresh", action="store_true", help="redownload pinned sources")
    mode.add_argument("--offline", action="store_true", help="use cached sources only")
    args = parser.parse_args()
    tables = {
        name: db2(name, args.refresh, args.offline)
        for name in ("SpellEffect", "ItemXItemEffect", "ItemEffect", "SpellMisc", "SpellRange")
    }
    friendly, hostile = band_spells(tables["SpellEffect"])
    items = band_items(
        tables["ItemXItemEffect"],
        tables["ItemEffect"],
        tables["SpellMisc"],
        tables["SpellRange"],
        friendly,
        hostile,
    )
    publish({OUTPUT: render_targets(friendly, hostile, items)})
    print(f"Targets: {len(friendly)} friendly spells, {len(hostile)} hostile spells, {len(items)} items")


if __name__ == "__main__":
    main()
