import json
import tempfile
import unittest
from pathlib import Path

from tools import check_nav
from tools.pack_nav import FIELDS, read_packed, write_bundle
from tools.refresh_nav_graph import COMPATIBILITY, collision_digest, refresh_digest

HEADER = """-- Generated by tools/baker/gen_nav.py.
-- Source: local wowf 1.60.1.70862, TrinityCore abc123, recipe {recipe}.
-- Generator: {generator}.
-- Map 0 (Eastern Kingdoms), mmtile rows 20-61 x cols 23-45.
return {{}}
"""


def recipe(product, build, map_id):
    return f"{product}{build}{map_id}".replace(".", "")


class CheckNavTest(unittest.TestCase):
    def root(self, **files):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        root = Path(directory.name)
        (root / "Nav").mkdir()
        for name, text in files.items():
            (root / "Nav" / f"{name}.lua").write_text(text)
        return root

    def check(self, root):
        return check_nav.problems(root, generator="gen", recipe=recipe)

    def test_a_map_from_the_pinned_recipe_and_generator_passes(self):
        root = self.root(Nav0=HEADER.format(recipe="wowf1601708620", generator="gen"), Nav0_1="return {}\n")
        self.assertEqual(self.check(root), [])

    def test_a_changed_pin_or_generator_fails(self):
        root = self.root(Nav0=HEADER.format(recipe="old", generator="older"))
        self.assertEqual(len(self.check(root)), 2)

    def test_a_map_without_provenance_fails(self):
        root = self.root(Nav1="-- Map 1 (Kalimdor).\nreturn {}\n")
        self.assertIn("names no baked source", self.check(root)[0])

    def test_build_mode_reports_maps_behind_the_newest_build(self):
        root = self.root(Nav0=HEADER.format(recipe="r", generator="g"))
        self.assertEqual(check_nav.behind("1.60.1.70862", root), [])
        self.assertEqual(len(check_nav.behind("1.60.2.1", root)), 1)

    def test_graph_refresh_checks_its_code_roads_and_actual_packed_collision_input(self):
        root = self.root()
        (root / "Data").mkdir()
        roads = root / "Data" / "RoadCells.lua"
        roads.write_text("roads input\n")
        fields = {name: {} for name in FIELDS}
        fields["grid"], fields["height"] = {1: "Q"}, {1: "X"}
        original = json.loads(COMPATIBILITY.read_text())["collision_generators"][0]
        header = HEADER.format(recipe="wowf1601708620", generator=original)
        header = header.replace(
            "-- Map ",
            f"-- Graph generator: {refresh_digest(root)}.\n-- Graph input: {collision_digest(fields)}.\n-- Map ",
        )
        source = root / "Nav0.lua"
        source.write_text(
            header.replace(
                "return {}",
                "ShortestPathForeverPathData[0] = {\n"
                + "".join(
                    f"\t{name} = {{\n" + "".join(f'\t\t[{k}] = "{v}",\n' for k, v in fields[name].items()) + "\t},\n"
                    for name in FIELDS
                )
                + "}",
            )
        )
        write_bundle(root, [source])
        self.assertEqual(read_packed(root / "Nav" / "Nav0.lua", 0)[1], fields)
        check = lambda: check_nav.problems(root, recipe=recipe)  # noqa: E731
        self.assertEqual(check(), [])
        self.assertIn(
            "collision producer changed", check_nav.problems(root, generator="futureGeometry", recipe=recipe)[0]
        )
        roads.write_text("changed roads\n")
        self.assertIn("other graph-refresh code or road data", check()[0])
        roads.write_text("roads input\n")
        # Repack changed collision data under the unchanged input hash.
        write_bundle(root, [root / "Nav" / "Nav0.lua"], extra={0: {"grid": {1: "R"}}})
        self.assertIn("differs from its collision fields", check()[0])

    def test_an_incomplete_graph_refresh_header_fails(self):
        root = self.root(
            Nav0=HEADER.format(recipe="wowf1601708620", generator="gen").replace(
                "-- Map ", "-- Graph input: invalid.\n-- Map "
            )
        )
        (root / "Data").mkdir()
        (root / "Data" / "RoadCells.lua").write_text("roads\n")
        self.assertTrue(self.check(root))


if __name__ == "__main__":
    unittest.main()
