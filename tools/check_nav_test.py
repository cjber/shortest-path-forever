import tempfile
import unittest
from pathlib import Path

from tools import check_nav

HEADER = """-- Generated by tools/baker/gen_nav.py.
-- Source: local wowf 1.60.1.70862, TrinityCore abc123, recipe {recipe}.
-- Generator: {generator}.
-- Map 0 (Eastern Kingdoms), mmtile rows 20-61 x cols 23-45.
return {{}}
"""


def recipe(product, build, map_id):
    return f"{product}{build}{map_id}".replace(".", "")


class CheckNavTest(unittest.TestCase):
    def root(self, **files):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        root = Path(directory.name)
        (root / "Nav").mkdir()
        for name, text in files.items():
            (root / "Nav" / f"{name}.lua").write_text(text)
        return root

    def check(self, root):
        return check_nav.problems(root, generator="gen", recipe=recipe)

    def test_a_map_from_the_pinned_recipe_and_generator_passes(self):
        root = self.root(Nav0=HEADER.format(recipe="wowf1601708620", generator="gen"), Nav0_1="return {}\n")
        self.assertEqual(self.check(root), [])

    def test_a_changed_pin_or_generator_fails(self):
        root = self.root(Nav0=HEADER.format(recipe="old", generator="older"))
        self.assertEqual(len(self.check(root)), 2)

    def test_a_map_without_provenance_fails(self):
        root = self.root(Nav1="-- Map 1 (Kalimdor).\nreturn {}\n")
        self.assertIn("names no baked source", self.check(root)[0])

    def test_build_mode_reports_maps_behind_the_newest_build(self):
        root = self.root(Nav0=HEADER.format(recipe="r", generator="g"))
        self.assertEqual(check_nav.behind("1.60.1.70862", root), [])
        self.assertEqual(len(check_nav.behind("1.60.2.1", root)), 1)


if __name__ == "__main__":
    unittest.main()
