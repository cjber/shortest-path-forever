-- Each baked walk's share in every zone and town along its straight way (Journey/Hazards.lua Shares), so a first
-- plan weighs thousands of baked walks by a short sum instead of sampling the way of each one. Run from the repo
-- root after changing the places, the zones or the zone cells:
-- luajit tools/bake_walk_zones.lua > Data/WalkZones.lua
local ns = { Init = function() end, db = {} }
for _, file in ipairs({
	"Data/Routes.lua",
	"Data/Transports.lua",
	"Data/Taxi.lua",
	"Data/Portals.lua",
	"Data/Teleports.lua",
	"Data/Zones.lua",
	"Data/ZoneCells.lua",
	"Data/TownAreas.lua",
	"Data/Walks.lua",
	"Journey/Hazards.lua",
}) do
	assert(loadfile(file))("ShortestPathForever", ns)
end
-- Every square of a map in Data/ZoneCells.lua is baked; a walk on another map keeps sampling in game.
ns.ZoneMap = function(map)
	error("no baked zone cells for this square of map " .. map)
end

local places = assert(loadfile("tools/walk_places.lua"))(ns)
local maps = {}
for map in pairs(ns.Walks) do
	if ns.ZoneCells[map] then
		maps[#maps + 1] = map
	end
end
table.sort(maps)
print("-- Generated by tools/bake_walk_zones.lua — do not edit.")
print("---@type string, SPFNamespace")
print("local _, ns = ...")
print("")
print(
	"-- [map][walk] = { zone, share, …, -flight master, share, … }: the share of the straight way between a baked"
)
print("-- walk's ends in each zone and in each town either side can meet.")
print("-- stylua: ignore")
print("ns.WalkZones = {")
for _, map in ipairs(maps) do
	local points = {}
	for _, place in ipairs(places[map]) do
		points[place.key] = place.point
	end
	local keys = {}
	for key in pairs(ns.Walks[map]) do
		keys[#keys + 1] = key
	end
	table.sort(keys)
	print(("\t[%d] = {"):format(map))
	for _, key in ipairs(keys) do
		local a, b = key:match("^(%S+) (%S+)$")
		a, b = assert(points[a], key), assert(points[b], key)
		local shares = ns.Hazards.Shares(map, a.x, a.y, b.x, b.y)
		local parts = {}
		for k = 1, #shares, 2 do
			-- Four places: the walks' own yards are whole, so a share finer than a ten-thousandth weighs nothing.
			local share = ("%.4f"):format(shares[k + 1]):gsub("0+$", ""):gsub("%.$", "")
			if share ~= "0" then
				parts[#parts + 1] = shares[k] .. ", " .. share
			end
		end
		if #parts > 0 then
			print(('\t\t["%s"] = { %s },'):format(key, table.concat(parts, ", ")))
		end
	end
	print("\t},")
end
print("}")
