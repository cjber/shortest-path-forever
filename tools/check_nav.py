"""Fail when a checked-in walking map is stale against this checkout's baker.

Each Nav/Nav<map>.lua header names the native recipe it was baked from (the TrinityCore pin, its patches and the
extractor commands, for one client build) and the digest of the generator code that turned that extract into the
map. Both are recomputed from this checkout; a mismatch means the map no longer matches its own source and has to be
rebaked with tools/baker/bake.sh. A newer client build does not fail a PR: the daily refresh runs this with
`--build <newest>` and keeps an issue open while any map is baked from an older build.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from baker.inputs import generator_digest  # noqa: E402
from baker.trinity import pinned_recipe  # noqa: E402

SOURCE = re.compile(r"-- Source: local (\S+) (\S+), TrinityCore (\w+), recipe (\w+)\.")
GENERATOR = re.compile(r"-- Generator: (\w+)\.")
MAP = re.compile(r"-- Map (\d+) ")
BASE = re.compile(r"Nav\d+\.lua")
REBAKE = "rebake it with tools/baker/bake.sh"


def header(path: Path) -> list[str]:
    """The comment lines a map file opens with."""
    lines = []
    with path.open() as stream:
        for line in stream:
            if not line.startswith("--"):
                break
            lines.append(line.rstrip("\n"))
    return lines


def provenance(lines: list[str]) -> dict:
    """The source, generator and map fields of a header, each None when absent."""
    found = {"source": None, "generator": None, "map": None}
    for line in lines:
        if m := SOURCE.fullmatch(line):
            found["source"] = m.groups()
        elif m := GENERATOR.fullmatch(line):
            found["generator"] = m.group(1)
        elif m := MAP.match(line):
            found["map"] = int(m.group(1))
    return found


def problems(root: Path = ROOT, generator: str | None = None, recipe=pinned_recipe) -> list[str]:
    generator = generator or generator_digest()
    found = []
    for path in sorted((root / "Nav").glob("Nav*.lua")):
        if not BASE.fullmatch(path.name):
            continue
        name = f"Nav/{path.name}"
        fields = provenance(header(path))
        if fields["source"] is None or fields["generator"] is None or fields["map"] is None:
            found.append(f"{name} names no baked source and generator; {REBAKE}")
            continue
        product, build, _, digest = fields["source"]
        if digest != recipe(product, build, fields["map"]):
            found.append(f"{name} was baked from another TrinityCore pin, patch or extractor command; {REBAKE}")
        if fields["generator"] != generator:
            found.append(f"{name} was generated by other tools/baker code; {REBAKE}")
    return found


def behind(build: str, root: Path = ROOT) -> list[str]:
    """Maps baked from a client build other than `build`."""
    found = []
    for path in sorted((root / "Nav").glob("Nav*.lua")):
        if BASE.fullmatch(path.name):
            source = provenance(header(path))["source"]
            baked = source[1] if source else "an unknown build"
            if baked != build:
                found.append(f"Nav/{path.name} was baked from {baked}, not {build}")
    return found


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", help="report maps baked from another client build instead")
    args = parser.parse_args()
    found = behind(args.build) if args.build else problems()
    for line in found:
        print(line, file=sys.stderr)
    if found:
        sys.exit(1)
    print(f"Walking maps are baked from {args.build}." if args.build else "Walking maps match this checkout's baker.")


if __name__ == "__main__":
    main()
