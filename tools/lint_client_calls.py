"""Refuse calls of client functions the Forever client does not answer (forever_tools.client_calls).

LuaLS checks against the retail annotations and only types/ adds to them, so a retail-only function type-checks and
then fails in game with `attempt to call a nil value`. This lint checks every bare global the runtime files call and
every `C_X.Y` they read against the client's own list (`forever_tools/client_names.txt`, generated by
tools/gen_forever_api.py), the Lua and WoW globals in the pinned annotations, the globals this addon and ForeverCore
define, and the global functions this addon's `tools/client_optional.txt` declares for an optional dependency. A
deliberate exception carries `-- client-ok: <reason>`; a waiver that excuses nothing fails.
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# forever_tools is tools/forever_tools in a consumer and the skill pack's tooling in forever-core.
TOOLS = Path(__file__).resolve().parent
for _base in (TOOLS, TOOLS.parent / ".agents/skills/wow-forever-addon/tooling"):
    if (_base / "forever_tools" / "client_calls.py").is_file():
        if str(_base) not in sys.path:
            sys.path.insert(0, str(_base))
        break

from forever_tools import client_calls  # noqa: E402

ANNOTATIONS = ROOT / ".types" / "vscode-wow-api"


def core_root() -> Path:
    """This checkout when it is ForeverCore itself, else the pinned ForeverCore checkout `FOREVER_CORE` names."""
    if (ROOT / "ForeverCore.toc").is_file():
        return ROOT
    core = Path(os.environ.get("FOREVER_CORE", ROOT.parent / "forever-core")).expanduser()
    if not (core / "ForeverCore.toc").is_file():
        raise SystemExit(f"FOREVER_CORE does not name a ForeverCore checkout: {core}")
    return core


def main() -> int:
    if not ANNOTATIONS.is_dir():
        raise SystemExit(f"{ANNOTATIONS} is missing; run tools/typecheck.sh, which fetches the pinned annotations")
    paths, environment = client_calls.environment(
        ROOT, annotations=ANNOTATIONS, api=client_calls.NAMES_FILE, core=core_root()
    )
    if sys.argv[1:]:
        return client_calls.run(ROOT, [Path(argument) for argument in sys.argv[1:]], environment)
    return client_calls.run(ROOT, paths, environment)


if __name__ == "__main__":
    sys.exit(main())
